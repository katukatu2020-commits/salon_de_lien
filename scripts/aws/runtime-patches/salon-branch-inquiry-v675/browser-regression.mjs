import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
const require = createRequire(process.env.SMOKE_DEPENDENCIES_PACKAGE)
const { chromium } = require('playwright-core')
const fixture = JSON.parse(fs.readFileSync(process.env.BROWSER_FIXTURE, 'utf8'))
const base = process.env.SMOKE_BASE_URL || fixture.base
const out = process.env.SCREENSHOT_DIR || 'artifacts/salon-branch-inquiry-v675/browser'
fs.mkdirSync(out, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--no-sandbox'] })
const errors = []
try {
  for (const [width, height] of [[1440, 1000], [390, 844], [360, 780]]) {
    const context = await browser.newContext({ viewport: { width, height } })
    const page = await context.newPage()
    page.on('pageerror', error => errors.push(error.message))
    assert.equal((await context.request.post(base + '/fixture/login', { data: { loginId: 'owner-a', password: 'Fixture-v672-Only!' } })).status(), 200)
    await page.goto(base + '/admin/salon-master?month=2026-09')
    const open = page.getByRole('button', { name: '新店舗を登録', exact: true })
    assert.equal(await open.isEnabled(), true, 'No subscription plan must not disable inquiry')
    await open.click()
    const dialog = page.locator('#sg-create')
    await dialog.waitFor({ state: 'visible' })
    assert.equal(await page.locator('dialog[open]').count(), 1)
    await page.getByRole('button', { name: '運営に申請する', exact: true }).click()
    assert.equal(await dialog.locator('input:invalid').count() > 0, true)
    const name = 'ブラウザー検証 ' + width + ' ' + Date.now()
    await dialog.getByLabel('新店舗名', { exact: true }).fill(name)
    await dialog.getByLabel('店舗管理者名', { exact: true }).fill('検証 管理者')
    await dialog.getByLabel('連絡先メール', { exact: true }).fill('browser-' + width + '@example.test')
    await dialog.getByLabel('電話番号', { exact: true }).fill('086-123-4567')
    await dialog.getByLabel('都道府県', { exact: true }).selectOption('岡山県')
    await dialog.getByLabel('市区町村', { exact: true }).fill('岡山市北区')
    await dialog.getByLabel('町名・番地・建物名', { exact: true }).fill('表町1-2-3')
    await dialog.getByLabel('ご相談内容（任意）', { exact: true }).fill('新店舗登録を希望します。\n開店日についても相談したいです。')
    await dialog.getByRole('checkbox').check()
    const layout = await dialog.evaluate(el => ({ right: el.getBoundingClientRect().right, left: el.getBoundingClientRect().left, scroll: el.scrollWidth, client: el.clientWidth }))
    assert.ok(layout.left >= 0 && layout.right <= width && layout.scroll <= layout.client + 1, 'Dialog fits viewport')
    await dialog.evaluate(el => { el.scrollTop = 0 })
    await page.screenshot({ path: path.join(out, 'form-' + width + '.png') })
    const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/admin/salon-master/stores') && r.request().method() === 'POST')
    await dialog.getByRole('button', { name: '運営に申請する', exact: true }).click()
    const response = await responsePromise
    assert.equal(response.status(), 201)
    const result = await response.json()
    assert.ok(result.inquiryId); assert.equal(result.initialPassword, undefined)
    await page.getByText('新店舗登録の申請を受け付けました', { exact: true }).waitFor()
    assert.equal(await dialog.locator('input:visible').count(), 0)
    await page.screenshot({ path: path.join(out, 'success-' + width + '.png') })
    await dialog.getByRole('button', { name: '閉じる', exact: true }).click()
    await open.click()
    assert.equal(await dialog.getByLabel('新店舗名', { exact: true }).inputValue(), '')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: '既存店舗を連携', exact: true }).click()
    await page.locator('#sg-link').waitFor({ state: 'visible' })
    await page.keyboard.press('Escape')
    const operator = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const cookieParts = fixture.operatorCookie.split('=')
    await operator.addCookies([{ name: cookieParts[0], value: cookieParts[1], url: base }])
    const admin = await operator.newPage()
    await admin.goto(base + '/platform/inquiries?q=' + encodeURIComponent(name))
    const card = admin.locator('.baaInquiry').filter({ hasText: name })
    assert.equal(await card.count(), 1)
    assert.match(await card.innerText(), /系列店の新店舗登録/)
    assert.match(await card.innerText(), /新店舗登録を希望します/)
    assert.match(await card.innerText(), /未対応/)
    if (width === 1440) await card.screenshot({ path: path.join(out, 'operator-inquiry.png') })
    await operator.close(); await context.close()
  }
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ desktopAndMobile: true, noPlanDialog: true, validation: true, submitToOperator: true, dialogReset: true, existingLinkPreserved: true, noJavascriptErrors: true }))
} finally { await browser.close() }
