import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'
import fs from 'node:fs/promises'
import path from 'node:path'
const require = createRequire(import.meta.url)
const { chromium } = require('playwright-core')
const base = 'http://127.0.0.1:3188', container = 'orimia-qa-v680-app'
const fixture = action => JSON.parse(execFileSync('docker', ['exec', container, 'node', '/tmp/qa-v706.cjs', action], { encoding: 'utf8' }) || 'null')
execFileSync('docker', ['cp', fileURLToPath(new URL('./qa-fixture.cjs', import.meta.url)), container + ':/tmp/qa-v706.cjs'])
const targets = fixture('customers')
assert.equal(fixture('status').length, 0, 'Restore previous QA test first')
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const login = await context.request.post(base + '/api/auth/login', { form: { email: 'demo.owner', password: 'QaLocalOnly-v680!', next: '/admin/customers/messages' }, maxRedirects: 0 })
assert.equal(login.status(), 303)
const page = await context.newPage(); page.setDefaultTimeout(10000)
const output = path.resolve('artifacts/campaign-coupon-v706'); await fs.mkdir(output, { recursive: true })
try {
  await page.goto(base + '/admin/customers/messages')
  await page.waitForFunction(() => window.__broadcastConfirmV706 === true)
  await page.locator('[name="title"]').fill('QA-v706 配信確認')
  await page.locator('[name="body"]').fill('テスト環境のみの確認')
  await page.getByRole('button', { name: '配信対象を選択', exact: true }).click()
  for (const target of targets) await page.locator('[name="targetCustomerId"][value="' + target.id + '"]').check()
  await page.getByRole('button', { name: '選択を完了' }).click()
  assert.equal(await page.locator('[name="title"]').inputValue(), 'QA-v706 配信確認', 'Recipient picker must not submit')
  await page.locator('[name="couponEnabled"]').check()
  await page.locator('[name="couponTitle"]').fill('QA確認クーポン')
  await page.locator('[name="couponTargetMenu"]').fill('似合わせカット')
  await page.getByRole('button', { name: '対象顧客へ配信する', exact: true }).click()
  await page.locator('.bc-list').waitFor()
  assert.equal(await page.locator('.bc-list tbody tr').count(), 2)
  for (const target of targets) assert.ok((await page.locator('.bc-list').innerText()).includes(target.name))
  assert.equal(fixture('status').length, 0)
  await page.screenshot({ path: path.join(output, 'confirmation-desktop.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  const modal = await page.locator('.broadcast-confirm-v706').boundingBox()
  assert.ok(modal.x >= 0 && modal.x + modal.width <= 390)
  await page.screenshot({ path: path.join(output, 'confirmation-mobile.png') })
  await page.locator('[data-cancel]').click()
  assert.equal(fixture('status').length, 0)
  const formEntries = await page.locator('[name="couponEnabled"]').evaluate(input => [...new FormData(input.form)].filter(([, value]) => typeof value === 'string'))
  const postAction = async entries => { const multipart = new FormData(); for (const [key, value] of entries) multipart.append(key, value); return context.request.post(base + '/admin/customers/messages', { multipart, headers: { Origin: base }, maxRedirects: 0 }) }
  const direct = await postAction(formEntries)
  assert.equal(direct.status(), 303)
  assert.ok(direct.headers().location.includes('confirmation-required'))
  assert.equal(fixture('status').length, 0, 'Server rejects unconfirmed delivery')
  const previewResponse = page.waitForResponse(response => response.url().endsWith('/api/admin/broadcast-preview') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '対象顧客へ配信する', exact: true }).click()
  const confirmed = await (await previewResponse).json()
  await page.locator('.bc-list').waitFor()
  await page.locator('[data-send]').click()
  await page.waitForURL(/notice=sent/)
  const sent = fixture('status')
  assert.equal(sent.length, 1); assert.equal(sent[0].recipients.length, 2)
  assert.deepEqual(sent[0].recipients.map(r => r.customerId).sort(), targets.map(r => r.id).sort())
  assert.ok(sent[0].recipients.every(r => r.couponIssueId))
  const replayEntries = new URLSearchParams(formEntries); replayEntries.set('broadcastConfirmationV706', confirmed.token)
  const replay = await postAction(replayEntries)
  assert.equal(replay.status(), 303)
  assert.ok(replay.headers().location.includes('already-sent'))
  assert.equal(fixture('status').length, 1, 'Retry cannot issue duplicate coupons')
  fixture('restore')
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport)
    await page.goto(base + '/admin/customers/messages/campaigns')
    await page.waitForFunction(() => document.querySelector('[data-campaign-coupon-v706]'))
    const source = await page.evaluate(() => {
      const c = document.createElement('canvas'); c.width = 800; c.height = 1200; const x = c.getContext('2d')
      x.fillStyle = '#eeeeee'; x.fillRect(0, 0, 800, 1200)
      for (const [color, left, top] of [['#ff0000',0,0],['#00ff00',700,0],['#0000ff',0,1100],['#ffff00',700,1100]]) { x.fillStyle = color; x.fillRect(left, top, 100, 100) }
      return c.toDataURL('image/png').split(',')[1]
    })
    await page.locator('#campaign-image').setInputFiles({ name: 'portrait.png', mimeType: 'image/png', buffer: Buffer.from(source, 'base64') })
    const editor = page.locator('.campaign-crop-v706')
    await editor.waitFor()
    const editorBox = await editor.locator('.lien-v293-dialog').boundingBox()
    assert.ok(editorBox.x >= 0 && editorBox.x + editorBox.width <= viewport.width, 'Crop editor fits viewport')
    await editor.locator('[name="zoom"]').evaluate(input => { input.value = '2'; input.dispatchEvent(new Event('input', { bubbles: true })) })
    await editor.locator('[name="y"]').evaluate(input => { input.value = '40'; input.dispatchEvent(new Event('input', { bubbles: true })) })
    const canvas = editor.locator('canvas'), box = await canvas.boundingBox()
    assert.ok(Math.abs(box.width / box.height - 4 / 3) < 0.01)
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 30, box.y + box.height / 2 + 40); await page.mouse.up()
    assert.notEqual(await editor.locator('[name="y"]').inputValue(), '40')
    await editor.locator('[data-fit]').click()
    const pixels = await canvas.evaluate(c => [ [310,20],[890,20],[310,880],[890,880] ].map(([x,y]) => [...c.getContext('2d').getImageData(x,y,1,1).data]))
    assert.deepEqual(pixels, [[255,0,0,255],[0,255,0,255],[0,0,255,255],[255,255,0,255]])
    await page.screenshot({ path: path.join(output, 'crop-' + viewport.width + '.png') })
    await editor.locator('[data-confirm]').click()
    await editor.waitFor({ state: 'detached' })
    const saved = await page.locator('#campaign-image').evaluate(async input => { const bitmap = await createImageBitmap(input.files[0]); return { width: bitmap.width, height: bitmap.height, type: input.files[0].type } })
    assert.deepEqual(saved, { width: 1200, height: 900, type: 'image/jpeg' })
    await page.locator('#campaign-preview img').waitFor()
    assert.equal(await page.locator('#campaign-preview img').evaluate(img => getComputedStyle(img).objectFit), 'contain')
    await page.locator('#campaign-image').setInputFiles({ name: 'cancel.png', mimeType: 'image/png', buffer: Buffer.from(source, 'base64') })
    await page.locator('.campaign-crop-v706 [data-cancel]').click()
    assert.equal(await page.locator('#campaign-image').evaluate(input => input.files.length), 0)
    assert.equal(await page.locator('#campaign-preview img').count(), 0, 'Cancel must not leave a misleading unsaved preview')
    assert.equal(await page.locator('#campaign-submit').isEnabled(), true)
  }
  console.log('PASS: recipient selection, confirmation/cancel/send with two coupons, responsive dialogs, crop zoom/drag/fit, exact 4:3 saved file and cancel.')
} finally { fixture('restore'); await browser.close() }
