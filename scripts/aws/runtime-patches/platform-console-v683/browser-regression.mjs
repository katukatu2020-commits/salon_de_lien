import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import {createRequire} from 'node:module'
const require=createRequire(process.env.SMOKE_DEPENDENCIES_PACKAGE||path.resolve('node_modules/playwright-core/package.json'))
const {chromium}=require('playwright-core')
const base=process.env.VERIFY_BASE_URL||'http://127.0.0.1:3191'
const output=path.resolve('artifacts/platform-console-v683')
fs.mkdirSync(output,{recursive:true})
const now=Math.floor(Date.now()/1000)
const payload=Buffer.from(JSON.stringify({version:1,role:'PLATFORM_OPERATOR',subject:'operator@example.test',issuedAt:now,expiresAt:now+3600,sessionId:crypto.randomUUID()})).toString('base64url')
const token=payload+'.'+crypto.createHmac('sha256','v679-fixture-only-secret-000000000000000000000000000').update(payload).digest('base64url')
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'})
try {
  const ctx=await browser.newContext({viewport:{width:1440,height:1000}})
  await ctx.addCookies([{name:'lien_platform_operator_session',value:token,url:base}])
  const page=await ctx.newPage(),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base+'/platform')
  assert.equal(await page.locator('.ops-brand img').evaluate(img=>img.complete&&img.naturalWidth>0),true)
  assert.equal(await page.locator('.ops-nav a[aria-current]').textContent(),'概要')
  assert.equal(await page.locator('table').count(),0)
  assert.equal(await page.locator('.ops-metric').count(),6)
  assert.ok((await page.locator('body').innerText()).includes('432,100円'))
  await page.screenshot({path:path.join(output,'overview-desktop.png'),fullPage:true})
  await page.locator('.ops-nav a[href="/platform/businesses"]').click()
  assert.equal(await page.locator('[data-business]').count(),6)
  assert.equal(await page.locator('[data-business="SALON:salon-a"]').count(),1)
  assert.equal(await page.locator('.fee-dashboard-payment').count(),6)
  const search=page.getByRole('searchbox')
  await search.focus()
  await search.dispatchEvent('compositionstart',{data:''})
  await search.fill('サロン')
  await page.waitForTimeout(600)
  assert.equal(await search.inputValue(),'サロン')
  assert.equal(await search.evaluate(el=>el===document.activeElement),true)
  await search.dispatchEvent('compositionend',{data:'サロン'})
  await page.getByRole('button',{name:'検索',exact:true}).click()
  assert.equal(await page.locator('[data-business]').count(),3)
  await page.goto(base+'/platform/businesses?type=SALON&state=ACTIVE')
  assert.equal(await page.locator('[data-business]').count(),3)
  await page.locator('[data-business="SALON:salon-a"] .ops-business-name').click()
  assert.equal(await page.locator('.ops-nav a[aria-current]').textContent(),'事業者管理')
  const text=await page.locator('body').innerText()
  for(const value of ['3,210,980円','123名','56件','4名','竹プラン','入金済み'])assert.ok(text.includes(value),value)
  assert.equal(await page.getByRole('button',{name:'店舗管理画面'}).count(),1)
  await page.locator('.ops-confirm summary').click()
  await page.getByRole('button',{name:'利用停止を確定'}).click()
  assert.ok(page.url().includes('/platform/businesses/salon/salon-a?account=suspended'))
  assert.equal(await page.getByRole('status').textContent(),'利用停止を反映しました。')
  assert.equal(await page.getByRole('button',{name:'店舗管理画面'}).count(),0)
  await page.locator('.ops-confirm summary').click()
  await page.getByRole('button',{name:'利用再開を確定'}).click()
  assert.equal(await page.getByRole('status').textContent(),'利用再開を反映しました。')
  await page.getByRole('link',{name:'支払い履歴',exact:true}).click()
  assert.equal(await page.locator('.ops-nav a[aria-current]').textContent(),'利用料・入金')
  assert.ok((await page.locator('body').innerText()).includes('入金済み'))
  for(const width of [1920,1440,768,390,320]) {
    await page.setViewportSize({width,height:1000})
    for(const [name,url] of [['overview','/platform'],['businesses','/platform/businesses?type=SALON'],['detail','/platform/businesses/salon/salon-a'],['payments','/platform/payments/salon/salon-a?month=2026-09']]) {
      const r=await page.goto(base+url)
      assert.equal(r.status(),200,url)
      const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)
      assert.equal(overflow,false,name+' overflow at '+width)
      const overlap=await page.locator('.ops-nav').evaluate(nav=>{const n=nav.getBoundingClientRect(),m=document.querySelector('main').getBoundingClientRect();return innerWidth>800&&m.left<n.right})
      assert.equal(overlap,false)
      if([1440,390].includes(width))await page.screenshot({path:path.join(output,name+'-'+width+'.png'),fullPage:true})
    }
  }
  assert.deepEqual(errors,[])
  await ctx.close()
  console.log('PASS v683 browser: navigation, unique business rows, Japanese input, filters, all detail metrics, confirmation + suspend/resume, fees, desktop/mobile widths 320-1920')
}finally{await browser.close()}
