import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
const require = createRequire(process.env.SMOKE_DEPENDENCIES_PACKAGE || '/tmp/browser/node_modules/playwright-core/package.json')
const { chromium } = require('playwright-core')
const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:3172'
const directory = process.env.SCREENSHOT_DIR || 'artifacts/salon-group-master-v672/browser'
fs.mkdirSync(directory, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const errors = []
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } })
  const login = await context.request.post(base + '/fixture/login', { data: { loginId: 'owner-a', password: 'Fixture-v672-Only!' } })
  assert.equal(login.status(), 200)
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  let accessRequests = 0
  page.on('request', req => { if (req.url().includes('/salon-master/access')) accessRequests++ })
  await page.goto(base + '/admin/settings')
  await page.getByRole('link', { name: 'マスタを開く' }).waitFor()
  await page.getByLabel('店舗名', { exact: true }).fill('編集中の店舗名')
  await page.waitForTimeout(500)
  assert.equal(await page.getByLabel('店舗名', { exact: true }).inputValue(), '編集中の店舗名')
  assert.equal(accessRequests, 1, 'settings observers must not loop requests')
  await page.getByRole('link', { name: 'マスタを開く' }).click()
  await page.locator('input[name=month]').fill('2026-09')
  await page.getByRole('button', { name: '表示', exact: true }).click()
  await page.locator('.sg-metric.revenue strong').filter({ hasText: '27,000円' }).waitFor()
  assert.equal(await page.locator('.sg-bar').count(), 12)
  assert.ok(await page.locator('.sg-bar.current').evaluate(el => el.getBoundingClientRect().height) > 0)
  assert.ok(await page.locator('.sg-brand img').evaluate(el => el.complete && el.naturalWidth > 0))
  await page.screenshot({ path: path.join(directory, 'desktop.png'), fullPage: true })
  await page.locator('select[name=store]').selectOption('org-b')
  await page.getByRole('button', { name: '表示', exact: true }).click()
  await page.locator('.sg-metric.revenue strong').filter({ hasText: '12,000円' }).waitFor()
  assert.equal(await page.locator('.sg-table tbody tr').count(), 1)
  await page.getByRole('button', { name: '既存店舗を連携', exact: true }).click()
  await page.locator('#sg-link-form input[name=loginId]').fill('owner-c')
  await page.locator('#sg-link-form input[name=password]').fill('wrong')
  await page.locator('#sg-link-form input[type=checkbox]').check()
  await page.getByRole('button', { name: '認証して連携' }).click()
  await page.locator('#sg-link-form .sg-feedback').filter({ hasText: '確認してください' }).waitFor()
  assert.equal(await page.locator('#sg-link-form input[name=loginId]').inputValue(), 'owner-c')
  await page.locator('#sg-link-form input[name=password]').fill('Fixture-v672-Only!')
  await page.getByRole('button', { name: '認証して連携' }).click()
  await page.waitForURL(base + '/admin/salon-master')
  assert.ok(await page.locator('.sg-table').innerText().then(text => text.includes('Salon de Lien 倉敷')))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(base + '/admin/salon-master?month=2026-09')
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.screenshot({ path: path.join(directory, 'mobile.png'), fullPage: true })
  await page.getByRole('button', { name: '新店舗を登録', exact: true }).click()
  const form = page.locator('#sg-create-form')
  const inputs = { name: 'ブラウザ検証 新店舗', ownerName: '検証 管理者', email: 'browser@example.test', phone: '086-123-4567', city: '倉敷市', address: '美観地区1-2-3' }
  for (const [name, value] of Object.entries(inputs)) await form.locator(`[name=${name}]`).fill(value)
  await form.locator('[name=prefecture]').selectOption('岡山県')
  await page.screenshot({ path: path.join(directory, 'mobile-register.png') })
  assert.ok(await page.locator('#sg-create').evaluate(el => el.scrollWidth <= el.clientWidth + 1))
  await form.locator('[name=confirmed]').check()
  await form.getByRole('button', { name: '登録する', exact: true }).click()
  await page.getByRole('heading', { name: '新店舗を登録しました' }).waitFor()
  assert.ok((await page.getByLabel('初期パスワード', { exact: true }).inputValue()).length > 15)
  const newLoginId = await page.locator('#sg-created').getByLabel('ログインID', { exact: true }).inputValue()
  assert.match(newLoginId, /^salon-/)
  await page.getByRole('link', { name: '店舗一覧へ戻る' }).click()
  await page.waitForURL(base + '/admin/salon-master')
  assert.match(await page.locator('.sg-table').innerText(), /ブラウザ検証 新店舗/)
  await page.setViewportSize({ width: 360, height: 740 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.screenshot({ path: path.join(directory, 'mobile-360.png'), fullPage: true })
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ release: 'salon-group-master-v672', desktop: true, mobile390: true, mobile360: true, filters: true, existingStoreLink: true, branchRegistration: true, stableInputs: true, noPageErrors: true }))
} finally { await browser.close() }
