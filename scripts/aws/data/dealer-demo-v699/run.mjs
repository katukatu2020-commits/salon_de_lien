import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { gzipSync } from 'node:zlib';
import { execFileSync } from 'node:child_process';
const region='ap-northeast-1',cluster='salon-de-lien-staging-cluster';
const aws=(args)=>JSON.parse(execFileSync('aws',[...args,'--region',region,'--output','json','--no-cli-pager'],{encoding:'utf8',maxBuffer:2000000}));
const service=aws(['ecs','describe-services','--cluster',cluster,'--services','salon-de-lien-staging-web']).services[0];
const definition=aws(['ecs','describe-task-definition','--task-definition',service.taskDefinition]).taskDefinition;
const web=definition.containerDefinitions.find(c=>c.name==='Web');
if(!web.image.includes('dealer-order-flow-v698-'))throw Error('Production version changed; review before continuing');
const code=fs.readFileSync(new URL('./audit.cjs',import.meta.url),'utf8');
const compressed=gzipSync(code).toString('base64');
const overrides={containerOverrides:[{name:'Web',command:['node','-e',`eval(require('node:zlib').gunzipSync(Buffer.from('${compressed}','base64')).toString())`]}]};
if(Buffer.byteLength(JSON.stringify(overrides))>8100)throw Error('ECS override too large');
const root=process.env.RUNNER_TEMP || os.tmpdir();
const network=path.join(root,'demo-v699-network.json'),override=path.join(root,'demo-v699-overrides.json');
fs.writeFileSync(network,JSON.stringify(service.networkConfiguration));
fs.writeFileSync(override,JSON.stringify(overrides));
const started=aws(['ecs','run-task','--cluster',cluster,'--task-definition',service.taskDefinition,'--launch-type','FARGATE','--network-configuration','file://'+network,'--overrides','file://'+override]);
if(started.failures?.length||!started.tasks?.length)throw Error(JSON.stringify(started.failures));
const taskArn=started.tasks[0].taskArn;
console.log('Read-only audit task: '+taskArn);
execFileSync('aws',['ecs','wait','tasks-stopped','--cluster',cluster,'--tasks',taskArn,'--region',region,'--no-cli-pager'],{stdio:'inherit'});
const task=aws(['ecs','describe-tasks','--cluster',cluster,'--tasks',taskArn]).tasks[0];
const log=web.logConfiguration.options;
const stream=log['awslogs-stream-prefix']+'/Web/'+taskArn.split('/').at(-1);
const events=aws(['logs','get-log-events','--log-group-name',log['awslogs-group'],'--log-stream-name',stream]).events;
for(const e of events)if(e.message.startsWith('DEMO_AUDIT_V699 '))console.log(e.message);
if(task.containers.find(c=>c.name==='Web').exitCode!==0){for(const e of events)console.error(e.message);throw Error('Audit failed')}
